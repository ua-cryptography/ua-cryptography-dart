// Generates lib/src/bindings/ua_cryptography.g.dart from the C header of the pinned native release.
//
//   dart run tool/generate_bindings.dart                     # the header of the pinned release, from GitHub
//   dart run tool/generate_bindings.dart --header <path.h>   # a local header, e.g. of an unreleased change
import 'dart:io';

import 'package:ffigen/ffigen.dart';
import 'package:ua_cryptography/src/bindings/native_release.dart';

final Uri packageRoot = Platform.script.resolve('../');
final Uri bindingsPath = packageRoot.resolve('lib/src/bindings/ua_cryptography.g.dart');

Future<void> main(List<String> arguments) async {
  final header = switch (arguments) {
    ['--header', final path] => File(path).absolute,
    [] => await downloadPinnedHeader(),
    _ => throw ArgumentError('Usage: dart run tool/generate_bindings.dart [--header <path.h>]'),
  };
  final generator = FfiGenerator(
    input: Input(entryPoints: [header.uri], include: (included) => included == header.uri),
    output: Output(
      dart: DartOutput(path: bindingsPath),
      style: const NativeExternalBindings(assetId: nativeAssetId),
      commentType: const CommentType(CommentStyle.any, CommentLength.full),
      preamble:
          '''
// The C ABI of ua-cryptography-rust $nativeLibraryVersion. Generated by tool/generate_bindings.dart; do not edit.
// ignore_for_file: type=lint''',
    ),
    visitors: [
      Visitor(
        func: (node) => node.isIncluded = true,
        struct: (node) => node.isIncluded = true,
        enumClass: (node) {
          node.isIncluded = true;
          // UaStatus has values 0..6: a 4-byte int with clang, GCC and MSVC on every supported target.
          node.silenceWarning = true;
        },
        macroConstant: (node) => node.isIncluded = true,
        typealias: (node) => node.isIncluded = TypealiasInclude.always,
      ),
    ],
  );
  await generator.generate();
  // ffigen formats at its own width; the repository's width keeps a regeneration free of diffs.
  final format = await Process.run(Platform.resolvedExecutable, ['format', bindingsPath.toFilePath()]);
  if (format.exitCode != 0) {
    throw ProcessException('dart', ['format'], '${format.stderr}', format.exitCode);
  }
}

// The header the release was built with, at its tag: a header from a later commit could declare what the
// library does not export.
Future<File> downloadPinnedHeader() async {
  final url = Uri.parse(
    'https://raw.githubusercontent.com/ua-cryptography/ua-cryptography-rust/v$nativeLibraryVersion/'
    'crates/ua-cryptography-ffi/include/ua_cryptography.h',
  );
  final header = File.fromUri(
    packageRoot.resolve('.dart_tool/ua_cryptography/ua_cryptography-$nativeLibraryVersion.h'),
  );
  final client = HttpClient();
  try {
    final response = await (await client.getUrl(url)).close();
    if (response.statusCode != HttpStatus.ok) {
      throw HttpException('HTTP ${response.statusCode}', uri: url);
    }
    header.parent.createSync(recursive: true);
    await response.pipe(header.openWrite());
  } finally {
    client.close();
  }
  return header;
}
